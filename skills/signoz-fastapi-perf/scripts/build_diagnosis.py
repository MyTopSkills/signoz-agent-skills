#!/usr/bin/env python3
"""Build evidence-first Codex handoff from SigNoz analyzer output (stdlib only).

Reads analysis.json generated by collect_signoz.py. No network and no app writes.
"""
from __future__ import annotations
import argparse
import datetime as dt
import json
from collections import defaultdict
from pathlib import Path
from typing import Any


def as_float(value: Any, default: float = 0.0) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def as_int(value: Any, default: int = 0) -> int:
    try:
        return int(value)
    except (TypeError, ValueError):
        return default


def pattern_candidates(entry: dict) -> list[dict]:
    """Return investigative hypotheses, explicitly NOT proven root causes."""
    summary = entry.get("summary") or {}
    groups = entry.get("groups") or []
    repeated = entry.get("repeated_operations") or []
    patterns: list[dict] = []

    mongo_find_count = as_int(summary.get("mongo_find_count"))
    if mongo_find_count >= 10:
        patterns.append({
            "id": "repeated_mongodb_find",
            "confidence": "medium",
            "evidence": f"{mongo_find_count} MongoDB find Span(s) in one request",
            "verify_in_code": "Locate find/find_one calls in per-item loops, map async awaits and Mongo query keys; compare batch alternatives; inspect query plans",
            "not_proven": "Repeated find spans alone do not prove N+1 or an index defect",
        })
    slow_db = [g for g in groups if g.get("category") == "MongoDB" and as_float(g.get("max_ms")) >= 1000]
    if slow_db:
        top = max(slow_db, key=lambda g: as_float(g.get("max_ms")))
        patterns.append({
            "id": "long_mongodb_operation",
            "confidence": "high_observation_only",
            "evidence": f"MongoDB Span '{top.get('operation','')}' max {top.get('max_ms')} ms",
            "verify_in_code": "Locate exact MongoDB operation, measure server execution with safe explain or existing profiler evidence, check index selection and network/connection waiting",
            "not_proven": "Span duration includes client/network waiting and does not prove a slow server-side query",
        })
    slow_external = [g for g in groups if g.get("category") in {"S3", "External HTTP/Client", "OpenSearch"} and as_float(g.get("max_ms")) >= 1000]
    if slow_external:
        top = max(slow_external, key=lambda g: as_float(g.get("max_ms")))
        patterns.append({
            "id": "slow_external_dependency",
            "confidence": "high_observation_only",
            "evidence": f"{top.get('category')} span '{top.get('operation')}' max {top.get('max_ms')} ms",
            "verify_in_code": "Examine timeout, retries, resource size, client reuse, sequential await and upstream latency; do not assume server fault",
            "not_proven": "Trace shows long client operation, not why the external call was slow",
        })
    uncovered = as_float(summary.get("uncovered_ms"))
    pct = as_float(summary.get("uncovered_percent"))
    if uncovered >= 1000 and pct >= 25:
        patterns.append({
            "id": "root_span_coverage_gap",
            "confidence": "high_observation_only",
            "evidence": f"Root interval not covered by any descendant span: {uncovered:.1f} ms ({pct:.1f}%)",
            "verify_in_code": "Identify phase boundaries and add narrowly scoped business OTel spans; check uninstrumented IO, CPU, queueing and serialization",
            "not_proven": "Coverage gap is not CPU self-time or a confirmed root cause",
        })
    mongo_repeat = [g for g in repeated if g.get("category") == "MongoDB" and as_int(g.get("count")) >= 3]
    if mongo_repeat and not any(x["id"] == "repeated_mongodb_find" for x in patterns):
        top = max(mongo_repeat, key=lambda g: as_int(g.get("count")))
        patterns.append({
            "id": "repeated_mongodb_operations",
            "confidence": "medium",
            "evidence": f"'{top.get('operation')}' repeated {top.get('count')} times",
            "verify_in_code": "Check loops, duplicate lookups, shared caching scope and opportunity for safe batched reads",
            "not_proven": "Repeat count may reflect intentionally distinct database operations",
        })
    if entry.get("truncated_spans"):
        patterns.append({
            "id": "incomplete_trace",
            "confidence": "high_observation_only",
            "evidence": "Span fetch hit configured --max-spans bound",
            "verify_in_code": "Re-fetch trace with a larger bounded limit before making claims about complete call trees",
            "not_proven": "Current counts and uncovered intervals may be incomplete",
        })
    if not patterns:
        patterns.append({
            "id": "not_enough_evidence",
            "confidence": "low",
            "evidence": "No high-signal rule triggered from exported summary",
            "verify_in_code": "Inspect longest child span, self/uncovered span, trace waterfall and route implementation",
            "not_proven": "Absence of a rule hit does not mean the route is healthy",
        })
    return patterns


def rank_key(item: dict) -> tuple:
    # Sample frequency is not request frequency; only orders investigation candidates.
    return (item["slow_samples"], item["sample_max_ms"])


def build(entries: list[dict], source: Path, metadata: dict | None = None) -> dict:
    grouped: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for entry in entries:
        summary = entry.get("summary") or {}
        route = str(summary.get("endpoint") or "(unknown)")
        service = str(summary.get("service") or "(unknown)")
        grouped[(service, route)].append(entry)

    endpoints = []
    for (service, endpoint), traces in grouped.items():
        samples = []
        pattern_index: dict[str, dict] = {}
        for entry in sorted(traces, key=lambda t: as_float((t.get("summary") or {}).get("latency_ms")), reverse=True):
            s = entry.get("summary") or {}
            trace_id = str(s.get("trace_id") or "")
            matches = pattern_candidates(entry)
            for p in matches:
                idx = p["id"]
                if idx not in pattern_index:
                    pattern_index[idx] = {**p, "observed_trace_ids": []}
                if trace_id and trace_id not in pattern_index[idx]["observed_trace_ids"]:
                    pattern_index[idx]["observed_trace_ids"].append(trace_id)
            samples.append({
                "trace_id": trace_id,
                "timestamp_utc": s.get("timestamp_utc", ""),
                "latency_ms": as_float(s.get("latency_ms")),
                "span_count": as_int(s.get("span_count")),
                "mongo_count": as_int(s.get("mongo_count")),
                "mongo_find_count": as_int(s.get("mongo_find_count")),
                "mongo_wall_ms": as_float(s.get("mongo_wall_ms")),
                "mongo_sum_ms": as_float(s.get("mongo_sum_ms")),
                "max_self_span": s.get("max_self_span", ""),
                "max_self_ms": as_float(s.get("max_self_ms")),
                "uncovered_ms": as_float(s.get("uncovered_ms")),
                "top_operation_groups": [
                    {"category": g.get("category"), "name": g.get("operation"), "count": as_int(g.get("count")),
                     "sum_ms": as_float(g.get("sum_ms")), "wall_union_ms": as_float(g.get("wall_union_ms")),
                     "max_ms": as_float(g.get("max_ms"))}
                    for g in (entry.get("groups") or [])[:8]
                ],
                "largest_root_coverage_gaps": (entry.get("top_gaps") or [])[:3],
                "truncated_spans": bool(entry.get("truncated_spans")),
                "hypothesis_ids": [p["id"] for p in matches],
            })
        duration_samples = [x["latency_ms"] for x in samples]
        endpoints.append({
            "service": service,
            "endpoint": endpoint,
            "slow_samples": len(samples),
            "sample_avg_ms": round(sum(duration_samples)/len(duration_samples), 1),
            "sample_max_ms": max(duration_samples),
            "sample_mongo_avg_calls": round(sum(x["mongo_count"] for x in samples)/len(samples), 1),
            "hypotheses_to_verify": list(pattern_index.values()),
            "code_locations": [],
            "source_code_verified": False,
            "sample_traces": samples[:8],
            "traces_not_included_in_detail": max(0,len(samples)-8),
        })
    endpoints.sort(key=rank_key,reverse=True)
    return {
        "schema_version": "1.0",
        "generated_at_utc": dt.datetime.now(dt.timezone.utc).isoformat(),
        "source": "SigNoz trace samples processed locally; no repository source code analyzed",
        "source_file": source.name,
        "collection_metadata": metadata or {},
        "limitations": [
            "Only sampled/limited slow requests are represented; counts are NOT total request traffic or endpoint-wide rates",
            "P50/P95/P99 over all requests cannot be derived from a slow-only sample",
            "Parent/child relationships and partial sampling may miss spans; a truncated trace weakens conclusions",
            "Overlapping/nested spans cannot be summed into HTTP wall time; Mongo sum_ms is not exclusive wall time",
            "Uninstrumented gaps/self time are not necessarily CPU, and automatic hints are hypotheses only",
            "No code location, business impact, MongoDB index defect, or optimization gain has been verified",
        ],
        "total_slow_request_samples": len(entries),
        "endpoint_count": len(endpoints),
        "endpoints": endpoints,
    }


def to_markdown(data: dict) -> str:
    lines = [
        "# SigNoz → Codex 性能诊断交接", "",
        f"生成时间 (UTC)：{data['generated_at_utc']}",
        "", "**证据边界：** 本文件来自慢请求采样和 Trace；它不等于全量请求统计，更未核实源代码。", "",
        "## 排查优先级（仅用于定位优先顺序）", "",
        "| 接口 | 慢样本数 | 慢样本均值(ms) | 最大(ms) | Mongo平均次数 | 候选问题 |",
        "|---|---:|---:|---:|---:|---|",
    ]
    for ep in data["endpoints"]:
        issue = ", ".join(p["id"] for p in ep["hypotheses_to_verify"][:3])
        name = ep["endpoint"].replace("|","\\|")
        lines.append(f"| `{name}` | {ep['slow_samples']} | {ep['sample_avg_ms']:.1f} | {ep['sample_max_ms']:.1f} | {ep['sample_mongo_avg_calls']:.1f} | {issue} |")
    lines.extend(["", "## 必须使用的源码分析步骤", "",
        "1. 先查根目录 `AGENTS.md`、框架与依赖，再按路由定位 Router → Service → Repository；如有多个服务，先确认负责服务。",
        "2. 逐个 Trace ID 复核 `analysis.json` 的 `groups/top_gaps` 与 `spans.csv` 的父子 Span；不要拿 sum_ms 当墙钟耗时。",
        "3. 验证疑似 N+1：追踪循环内查询、参数是否随项目变化、串并行关系、查询计划与合理索引；指出文件、函数、行号。",
        "4. 对长 Mongo/S3/HTTP Span 区分客户端等待、上游耗时、重试、连接池排队；未埋点时间先建议增量 Span。",
        "5. 逐条输出 Trace ID、证据、根因/假设、置信度、代码位置、最小改动方案和测试计划。", "",
        "**安全闸门：** 第一轮仅诊断，不修改业务代码、数据库索引、生产配置或数据；必要时写报告，改动实施需用户明确批准。",
        "", "## 优先检查的 Trace", "",
    ])
    for ep in data["endpoints"][:10]:
        lines.append(f"### {ep['endpoint']}")
        for t in ep["sample_traces"][:3]:
            lines.append(f"- `{t['trace_id']}`: {t['latency_ms']:.1f}ms; spans={t['span_count']}; Mongo={t['mongo_count']}; root gaps={t['uncovered_ms']:.1f}ms")
        for p in ep["hypotheses_to_verify"]:
            lines.append(f"- 待验证 `{p['id']}`（{p['confidence']}）：{p['evidence']}；检查：{p['verify_in_code']}")
        lines.append("")
    lines.extend(["## 需要输出的报告", "",
        "- `PERFORMANCE_ANALYSIS.md`：接口排名、量化 Trace 证据、源码具体位置、已证实问题/待证实假设、风险、测试与验证方案。",
        "- 对耗时改进的数字仅在有真实测试或对比 Trace 后填写，不虚构百分比；不能从慢样本估算总体 P95。",
        "- 优化前后对比要同环境、同负载及相近输入；先回归响应结构、权限和业务结果。", "",
    ])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Build Codex diagnosis JSON + Markdown from SigNoz analysis.json")
    parser.add_argument("--report-dir", default=".perf-reports/latest")
    parser.add_argument("--output-dir", default=None, help="defaults to --report-dir")
    opts = parser.parse_args()
    report_dir = Path(opts.report_dir).expanduser().resolve()
    out_dir = Path(opts.output_dir).expanduser().resolve() if opts.output_dir else report_dir
    source = report_dir / "analysis.json"
    if not source.is_file():
        parser.error(f"未找到 {source}，请先运行 collect_signoz.py 采集，或指向已有报告目录")
    data = json.loads(source.read_text(encoding="utf-8"))
    if not isinstance(data,list):
        parser.error("analysis.json 必须是旧版采集器生成的数组结构")
    metadata_file = report_dir / "run_metadata.json"
    metadata = json.loads(metadata_file.read_text(encoding="utf-8")) if metadata_file.exists() else {}
    result = build(data,source,metadata)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir/"codex_diagnosis.json").write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding="utf-8")
    (out_dir/"CODEX_DIAGNOSIS.md").write_text(to_markdown(result),encoding="utf-8")
    print(f"Generated {out_dir/'codex_diagnosis.json'}")
    print(f"Generated {out_dir/'CODEX_DIAGNOSIS.md'}")
    print(f"{result['total_slow_request_samples']} slow samples across {result['endpoint_count']} endpoint(s)")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
